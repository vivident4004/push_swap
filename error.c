#include "dio.h"

void	error_free_exit(t_pila *a, t_pila *b)
{
	write(2, "Error\n", 6);
	free(a->v);
	free(b->v);
	exit(-1);
}

void	error_exit(void)
{
	write(2, "Error\n", 6);
	exit(-1);
}
